export type TranslationKey = keyof typeof TRANSLATIONS.es;
export type TranslationVars = Record<string, string | number>;

function interpolate(template: string, vars?: TranslationVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, token) =>
    Object.prototype.hasOwnProperty.call(vars, token) ? String(vars[token]) : match,
  );
}

export function t(key: TranslationKey, lang: Language = 'es', vars?: TranslationVars): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.es;
  const raw = dict[key] || TRANSLATIONS.es[key] || key;
  return interpolate(raw, vars);
}

export function useI18n() {
  const lang = useStore((s) => s.settings.language || 'es');
  return {
    lang,
    t: (key: TranslationKey, vars?: TranslationVars) => t(key, lang, vars),
  };
}
